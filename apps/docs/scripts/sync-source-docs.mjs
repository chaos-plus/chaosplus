#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { documents, routeFor } from './docs-map.mjs';

const scriptRoot = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptRoot, '../../..');
const outputRoot = path.join(repoRoot, 'apps/docs/src/content/docs');
const generatedMarker = '<!-- generated by scripts/sync-source-docs.mjs; edit the root source document -->';
const sourceRoutes = new Map();

for (const document of documents) {
	sourceRoutes.set(document.source.replaceAll('\\', '/'), routeFor(document.target));
	sourceRoutes.set(path.posix.basename(document.source), routeFor(document.target));
}

function rewriteLinks(markdown) {
	return markdown.replace(/\]\(([^)]+)\)/gu, (match, href) => {
		if (/^(?:[a-z]+:|#|\/)/iu.test(href)) return match;
		const [pathname, hash = ''] = href.split('#', 2);
		const normalized = pathname.replace(/^\.\//u, '').replace(/^\.\.\//u, '').replaceAll('\\', '/');
		const route = sourceRoutes.get(normalized) ?? sourceRoutes.get(path.posix.basename(normalized));
		return route ? `](${route}${hash ? `#${hash}` : ''})` : match;
	});
}

function render(document) {
	const sourcePath = path.join(repoRoot, document.source);
	let source = fs.readFileSync(sourcePath, 'utf8').replace(/\r\n/gu, '\n');
	source = source.replace(/^---\n[\s\S]*?\n---\n/u, '');
	const heading = source.match(/^#\s+(.+)$/mu)?.[1]?.trim();
	source = source.replace(/^#\s+.+\n+/mu, '');
	source = rewriteLinks(source).trim();
	const title = document.title || heading || path.basename(document.source, '.md');
	return `---\ntitle: ${JSON.stringify(title)}\ndescription: ${JSON.stringify(`由 ${document.source} 同步的工程文档`)}\neditUrl: false\n---\n\n${generatedMarker}\n\n${source}\n`;
}

let updated = 0;
for (const document of documents) {
	const targetPath = path.join(outputRoot, document.target);
	const next = render(document);
	const current = fs.existsSync(targetPath) ? fs.readFileSync(targetPath, 'utf8').replace(/\r\n/gu, '\n') : '';
	if (current === next) continue;
	fs.mkdirSync(path.dirname(targetPath), { recursive: true });
	fs.writeFileSync(targetPath, next);
	updated += 1;
}

console.log(updated ? `Synchronized ${updated} documentation page(s).` : 'Documentation sources are current.');
